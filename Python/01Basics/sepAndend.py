print('A', 'B', 'C', sep=',', end='!')
print(' D', 'E', 'F', sep='-', end=' ')
print('G', 'H', 'I', sep='+', end='\n')
print('J', 'K', 'L')



# end: Specifies the string appended after the last item is printed (default is \n, a newline).
# sep: Specifies the string inserted between multiple items being printed (default is a single space ' ')

# While end controls what happens after the output, sep controls the formatting between the arguments provided to the function.